#!/usr/bin/env python3
"""
AOT Assembly Peephole Optimizer for Brainfuck x86-64 Output.
Detects linear balanced loops generated by the Brainfuck compiler
(such as copy [->+>+<<], move [-<+>], multiply [->++++++++++<], etc.)
and lowers them directly into constant-time O(1) x86-64 arithmetic instructions.
"""

import sys

TAPE_CELLS = 256
OPS = set("><+-.,[]")


def audit_tape(program_file):
    """Prove the fixed server program never leaves its caller-provided tape."""
    with open(program_file, "r") as f:
        program = "".join(c for c in f.read() if c in OPS)

    def walk(pos):
        delta = low = high = 0
        while pos < len(program):
            op = program[pos]
            pos += 1
            if op == '>':
                delta += 1
            elif op == '<':
                delta -= 1
            elif op == '[':
                pos, loop_delta, loop_low, loop_high = walk(pos)
                if loop_delta:
                    raise ValueError("loop changes the tape pointer")
                low = min(low, delta + loop_low)
                high = max(high, delta + loop_high)
            elif op == ']':
                return pos, delta, low, high
            low = min(low, delta)
            high = max(high, delta)
        return pos, delta, low, high

    pos, _, low, high = walk(0)
    if pos != len(program):
        raise ValueError("unmatched closing bracket")
    if low < 0 or high >= TAPE_CELLS:
        raise ValueError(f"server uses tape cells [{low}, {high}], outside 0..{TAPE_CELLS - 1}")
    return low, high


def strip_proven_bounds_checks(asm_text):
    """Remove only compiler-emitted checks immediately following an r12 move."""
    lines = asm_text.splitlines()
    out = []
    removed = 0
    i = 0
    while i < len(lines):
        line = lines[i]
        if i + 2 < len(lines) and ("addq $" in line or "subq $" in line) and "%r12" in line:
            cmp_line = lines[i + 1].strip()
            branch_line = lines[i + 2].strip()
            upper = cmp_line == "cmpq %r15, %r12" and branch_line == "jae .L_tape_overflow"
            lower = cmp_line == "cmpq %r14, %r12" and branch_line == "jb .L_tape_underflow"
            if upper or lower:
                out.append(line)
                removed += 1
                i += 3
                continue
        # The compiler uses this temporary-address form for boolean lowering.
        # It is still a fixed displacement from r12 and is covered by the same
        # whole-program tape proof above.
        if i + 2 < len(lines) and line.strip().startswith("leaq ") and "(%r12), %rax" in line:
            cmp_line = lines[i + 1].strip()
            branch_line = lines[i + 2].strip()
            if cmp_line == "cmpq %r15, %rax" and branch_line == "jae .L_tape_overflow":
                removed += 1
                i += 3
                continue
        out.append(line)
        i += 1
    if removed == 0:
        raise ValueError("no compiler-emitted tape bounds checks found")
    return "\n".join(out), removed

def optimize_asm(asm_text):
    lines = asm_text.splitlines()
    i = 0
    out = []
    opt_count = 0
    while i < len(lines):
        line = lines[i]
        # Check if line starts a loop: cmpq $0, (%r12) followed by je .L_e_X and .L_s_X:
        if (line.strip() == "cmpq $0, (%r12)" and i + 2 < len(lines) and 
            lines[i+1].strip().startswith("je .L_e_") and 
            lines[i+2].strip().startswith(".L_s_")):
            end_label = lines[i+1].strip().split()[1]
            start_label = lines[i+2].strip()[:-1]
            label_id = start_label.split("_")[-1]
            if end_label == f".L_e_{label_id}":
                # Scan to find closing: cmpq $0, (%r12) \n jne .L_s_{label_id} \n .L_e_{label_id}:
                j = i + 3
                has_nested = False
                while j < len(lines):
                    if lines[j].strip().startswith(".L_s_"):
                        has_nested = True
                        break
                    if (lines[j].strip() == "cmpq $0, (%r12)" and j + 2 < len(lines) and
                        lines[j+1].strip() == f"jne {start_label}" and
                        lines[j+2].strip() == f"{end_label}:"):
                        break
                    j += 1
                if not has_nested and j < len(lines):
                    # Found innermost loop from i+3 to j
                    body_lines = [l.strip() for l in lines[i+3:j]]
                    if len(body_lines) > 0 and body_lines[0] == "decq (%r12)":
                        cur_offset = 0
                        deltas = {}
                        valid = True
                        for bl in body_lines[1:]:
                            if bl in ("cmpq %r14, %r12", "jb .L_tape_underflow", "cmpq %r15, %r12", "jae .L_tape_overflow"):
                                continue
                            if bl.startswith("addq $") and bl.endswith(", %r12"):
                                cur_offset += int(bl.split("$")[1].split(",")[0])
                            elif bl.startswith("subq $") and bl.endswith(", %r12"):
                                cur_offset -= int(bl.split("$")[1].split(",")[0])
                            elif bl == "incq (%r12)":
                                deltas[cur_offset] = deltas.get(cur_offset, 0) + 1
                            elif bl == "decq (%r12)":
                                deltas[cur_offset] = deltas.get(cur_offset, 0) - 1
                            elif bl.startswith("addq $") and bl.endswith(", (%r12)"):
                                deltas[cur_offset] = deltas.get(cur_offset, 0) + int(bl.split("$")[1].split(",")[0])
                            elif bl.startswith("subq $") and bl.endswith(", (%r12)"):
                                deltas[cur_offset] = deltas.get(cur_offset, 0) - int(bl.split("$")[1].split(",")[0])
                            else:
                                valid = False
                                break
                        if valid and cur_offset == 0 and 0 not in deltas and len(deltas) > 0:
                            # Optimize this linear loop to O(1) arithmetic!
                            opt_count += 1
                            out.append("    movq (%r12), %rax")
                            out.append("    testq %rax, %rax")
                            out.append(f"    jz {end_label}")
                            for off, factor in deltas.items():
                                if factor == 0: continue
                                off_str = f"{off}(%r12)" if off != 0 else "(%r12)"
                                if factor == 1:
                                    out.append(f"    addq %rax, {off_str}")
                                elif factor == -1:
                                    out.append(f"    subq %rax, {off_str}")
                                else:
                                    out.append(f"    imulq ${factor}, %rax, %rcx")
                                    out.append(f"    addq %rcx, {off_str}")
                            out.append("    movq $0, (%r12)")
                            out.append(f"{end_label}:")
                            i = j + 3
                            continue
        out.append(line)
        i += 1
    return "\n".join(out), opt_count

if __name__ == "__main__":
    if len(sys.argv) != 4:
        print("Usage: opt_bf_asm.py <input.s> <output.s> <server.bf>", file=sys.stderr)
        sys.exit(1)
    in_file = sys.argv[1]
    out_file = sys.argv[2]
    program_file = sys.argv[3]
    low, high = audit_tape(program_file)
    with open(in_file, "r") as f:
        src = f.read()
    opt, n = optimize_asm(src)
    opt, removed = strip_proven_bounds_checks(opt)
    with open(out_file, "w") as f:
        f.write(opt)
        f.write("\n")
    print(f"Peephole optimized {n} linear loops; verified tape cells {low}..{high}; removed {removed} redundant bound checks in {out_file}", file=sys.stderr)
