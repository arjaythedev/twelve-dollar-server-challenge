#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

// Brainfuck AOT Optimizing Compiler for BF-MMIO Architecture
void emit_bf_c(const char *bf_src, FILE *out) {
    fprintf(out, "// Auto-generated by Brainfuck AOT Compiler\n");
    fprintf(out, "#include <stdint.h>\n");
    fprintf(out, "#include <stddef.h>\n");
    fprintf(out, "#include <string.h>\n");
    fprintf(out, "#include \"runtime/bf_runtime.h\"\n\n");
    fprintf(out, "void bf_execute(int64_t *tape) {\n");
    fprintf(out, "    size_t ptr = 0;\n");

    const char *p = bf_src;
    while (*p) {
        switch (*p) {
            case '>': {
                int count = 0;
                while (*p == '>') { count++; p++; }
                fprintf(out, "    ptr += %d;\n", count);
                continue;
            }
            case '<': {
                int count = 0;
                while (*p == '<') { count++; p++; }
                fprintf(out, "    ptr -= %d;\n", count);
                continue;
            }
            case '+': {
                int count = 0;
                while (*p == '+') { count++; p++; }
                fprintf(out, "    tape[ptr] += %d;\n", count);
                fprintf(out, "    if (ptr == 7 && tape[7]) { bf_mmio_sys(tape); tape[7] = 0; }\n");
                fprintf(out, "    else if (ptr == 8 && tape[8]) { bf_mmio_crypto(tape); tape[8] = 0; }\n");
                fprintf(out, "    else if (ptr == 16 && tape[16]) { bf_mmio_db(tape); tape[16] = 0; }\n");
                fprintf(out, "    else if (ptr == 32 && tape[32]) { bf_mmio_net(tape); tape[32] = 0; }\n");
                continue;
            }
            case '-': {
                int count = 0;
                while (*p == '-') { count++; p++; }
                fprintf(out, "    tape[ptr] -= %d;\n", count);
                continue;
            }
            case '[': {
                if (p[1] == '-' && p[2] == ']') {
                    fprintf(out, "    tape[ptr] = 0;\n");
                    p += 3;
                    continue;
                }
                fprintf(out, "    while (tape[ptr]) {\n");
                p++;
                continue;
            }
            case ']': {
                fprintf(out, "    }\n");
                p++;
                continue;
            }
            case '.': {
                fprintf(out, "    bf_out_char((uint8_t)tape[ptr]);\n");
                p++;
                continue;
            }
            case ',': {
                fprintf(out, "    tape[ptr] = bf_in_char();\n");
                p++;
                continue;
            }
            default:
                p++;
                break;
        }
    }

    fprintf(out, "}\n");
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "Usage: %s <input.bf> <output.c>\n", argv[0]);
        return 1;
    }
    FILE *fin = fopen(argv[1], "rb");
    if (!fin) { perror("fopen input"); return 1; }
    fseek(fin, 0, SEEK_END);
    long sz = ftell(fin);
    fseek(fin, 0, SEEK_SET);
    char *src = malloc(sz + 1);
    fread(src, 1, sz, fin);
    src[sz] = 0;
    fclose(fin);

    FILE *fout = fopen(argv[2], "w");
    if (!fout) { perror("fopen output"); return 1; }
    emit_bf_c(src, fout);
    fclose(fout);
    free(src);
    return 0;
}
