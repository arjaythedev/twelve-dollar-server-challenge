package feed

import java.sql.{Connection, PreparedStatement}
import scala.collection.mutable

/** A prepared statement that survives `close()`. doobie closes every statement after use; here closing only clears the
  * parameters, so the next request with the same SQL skips SQLite's parse and plan. Reusing prepared statements caches
  * the query plan, not data (rule 5).
  */
final class ReusablePreparedStatement(underlying: PreparedStatement) extends PreparedStatement:
  export underlying.{close as _, isClosed as _, *}

  def close(): Unit = underlying.clearParameters()
  def isClosed: Boolean = false

  /** Really closes the statement, when its connection closes. */
  def dispose(): Unit = underlying.close()

/** A connection that prepares each SQL string once and hands out the same statement every time after that.
  *
  * Not thread-safe, and it doesn't need to be: the pool lends a connection to one request at a time.
  */
final class StatementCachingConnection(underlying: Connection) extends Connection:
  export underlying.{close as _, prepareStatement as _, *}

  private val statements = mutable.HashMap.empty[String, ReusablePreparedStatement]

  def prepareStatement(sql: String): PreparedStatement =
    statements.getOrElseUpdate(sql, ReusablePreparedStatement(underlying.prepareStatement(sql)))

  def prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement =
    underlying.prepareStatement(sql, autoGeneratedKeys)
  def prepareStatement(sql: String, columnIndexes: Array[Int]): PreparedStatement =
    underlying.prepareStatement(sql, columnIndexes)
  def prepareStatement(sql: String, columnNames: Array[String]): PreparedStatement =
    underlying.prepareStatement(sql, columnNames)
  def prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): PreparedStatement =
    underlying.prepareStatement(sql, resultSetType, resultSetConcurrency)
  def prepareStatement(sql: String, resultSetType: Int, concurrency: Int, holdability: Int): PreparedStatement =
    underlying.prepareStatement(sql, resultSetType, concurrency, holdability)

  def close(): Unit =
    statements.values.foreach(_.dispose())
    statements.clear()
    underlying.close()
